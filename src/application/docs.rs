use crate::cli::DocsArgs;
use crate::error::CliError;
use crate::inspection::InspectionContext;
use crate::manifest::model::Capability;
pub fn execute(args: &DocsArgs, output: &crate::cli::Output) -> Result<(), CliError> {
    let start = args
        .path
        .clone()
        .unwrap_or_else(|| std::env::current_dir().unwrap_or_default());
    let ctx = InspectionContext::build(&start)?;
    let manifest = ctx.manifest.as_ref().ok_or_else(|| {
        CliError::InvalidInput("project manifest is missing or invalid".to_string())
    })?;

    if !manifest.features.is_enabled(Capability::OpenApi) {
        return Err(CliError::InvalidInput(
            "OpenAPI documentation is not enabled in .rustrs/config.toml".to_string(),
        ));
    }

    if args.json {
        let value = serde_json::json!({
            "project_name": manifest.project_name,
            "openapi": manifest.features.openapi,
            "provider": "not generated by rustrs",
            "note": "Runtime documentation depends on the generated application and its dependencies."
        });
        output.info(&serde_json::to_string_pretty(&value).unwrap_or_default());
    } else {
        output.info("rustrs docs");
        output.info("");
        output.info(&format!("Project: {}", manifest.project_name));
        output.info("OpenAPI: enabled");
        output.info("Provider: configured by manifest only");
        output.info("Note: rustrs does not generate OpenAPI runtime code or endpoints in the current support matrix.");
    }

    let _ = ctx.project_root;
    Ok(())
}
