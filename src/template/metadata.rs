use crate::compatibility::CompatibilityError;
use crate::manifest::model::{Capability, TemplateId};
use std::path::Path;
use thiserror::Error;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AssetSource {
    Static(&'static str),
    Template(&'static str),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TemplateAsset {
    pub relative_path: &'static str,
    pub source: AssetSource,
    pub required: bool,
    pub condition: Option<Capability>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TemplateMetadata {
    pub id: TemplateId,
    pub version: &'static str,
    pub description: &'static str,
    pub assets: &'static [TemplateAsset],
}

#[derive(Debug, Error)]
pub enum TemplateError {
    #[error("template is not available: {template:?}")]
    Unavailable { template: TemplateId },

    #[error("template asset is missing: {template:?}: {path}")]
    MissingAsset { template: TemplateId, path: String },

    #[error("invalid template path: {path}")]
    InvalidPath { path: String },

    #[error("invalid template metadata: {message}")]
    InvalidMetadata { message: String },

    #[error("template context error: {message}")]
    Context { message: String },

    #[error("template render error: {message}")]
    Render { message: String },

    #[error("manifest error: {message}")]
    Manifest { message: String },

    #[error(transparent)]
    Compatibility(#[from] CompatibilityError),
}

impl TemplateMetadata {
    pub fn validate(&self) -> Result<(), TemplateError> {
        if self.version.is_empty() {
            return Err(TemplateError::InvalidMetadata {
                message: "template version must not be empty".to_string(),
            });
        }
        if self.description.is_empty() {
            return Err(TemplateError::InvalidMetadata {
                message: "template description must not be empty".to_string(),
            });
        }

        let mut seen = Vec::new();
        for asset in self.assets {
            if asset.relative_path.is_empty() {
                return Err(TemplateError::InvalidMetadata {
                    message: "asset relative_path must not be empty".to_string(),
                });
            }
            if seen.contains(&asset.relative_path) {
                return Err(TemplateError::InvalidMetadata {
                    message: format!("duplicate asset path: {}", asset.relative_path),
                });
            }
            seen.push(asset.relative_path);

            match asset.source {
                AssetSource::Static(source) | AssetSource::Template(source) => {
                    if asset.required && source.is_empty() {
                        return Err(TemplateError::MissingAsset {
                            template: self.id,
                            path: asset.relative_path.to_string(),
                        });
                    }
                }
            }

            let path = Path::new(asset.relative_path);
            if path.is_absolute() {
                return Err(TemplateError::InvalidPath {
                    path: asset.relative_path.to_string(),
                });
            }
            for component in path.components() {
                if !matches!(component, std::path::Component::Normal(_)) {
                    return Err(TemplateError::InvalidPath {
                        path: asset.relative_path.to_string(),
                    });
                }
            }
        }

        Ok(())
    }
}

