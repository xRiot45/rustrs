async fn issue_tokens(user_id: Uuid) -> Result<AuthResponse, StatusCode> {
    let now = Utc::now();
    let access_exp = (now + Duration::minutes(15)).timestamp() as usize;
    let refresh_exp = (now + Duration::days(7)).timestamp() as usize;

    let access_claims = Claims {
        sub: user_id.to_string(),
        exp: access_exp,
        token_type: "access".to_string(),
    };
    let refresh_claims = Claims {
        sub: user_id.to_string(),
        exp: refresh_exp,
        token_type: "refresh".to_string(),
    };

    let access_token = encode(
        &Header::default(),
        &access_claims,
        &EncodingKey::from_secret(jwt_secret().as_bytes()),
    )
    .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;
    let refresh_token = encode(
        &Header::default(),
        &refresh_claims,
        &EncodingKey::from_secret(jwt_secret().as_bytes()),
    )
    .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;

    let mut hasher = Sha256::new();
    hasher.update(refresh_token.as_bytes());
    let refresh_hash = format!("{:x}", hasher.finalize());

    let _ = store_refresh_token(user_id, refresh_hash, refresh_exp).await;
    Ok(AuthResponse {
        access_token,
        refresh_token,
    })
}

async fn store_refresh_token(
    user_id: Uuid,
    token_hash: String,
    exp: usize,
) -> Result<(), StatusCode> {
    let pool = db_pool().await?;
    let expires_at = chrono::DateTime::<Utc>::from_timestamp(exp as i64, 0)
        .ok_or(StatusCode::INTERNAL_SERVER_ERROR)?;
    sqlx::query(
        "INSERT INTO refresh_tokens (id, user_id, token_hash, expires_at, revoked) VALUES ($1, $2, $3, $4, false)",
    )
    .bind(Uuid::new_v4())
    .bind(user_id)
    .bind(token_hash.clone())
    .bind(expires_at)
    .execute(&pool)
    .await
    .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;
    Ok(())
}

async fn register(Json(req): Json<RegisterRequest>) -> impl IntoResponse {
    let pool = match db_pool().await {
        Ok(pool) => pool,
        Err(status) => return status.into_response(),
    };

    let salt = SaltString::generate(&mut OsRng);
    let password_hash = match Argon2::default().hash_password(req.password.as_bytes(), &salt) {
        Ok(hash) => hash.to_string(),
        Err(_) => return StatusCode::INTERNAL_SERVER_ERROR.into_response(),
    };

    let user_id = Uuid::new_v4();
    let result = sqlx::query(
        "INSERT INTO users (id, email, password_hash, role) VALUES ($1, $2, $3, $4)",
    )
    .bind(user_id)
    .bind(&req.email)
    .bind(&password_hash)
    .bind("user")
    .execute(&pool)
    .await;

    if result.is_err() {
        return StatusCode::CONFLICT.into_response();
    }

    match issue_tokens(user_id).await {
        Ok(response) => (StatusCode::CREATED, Json(response)).into_response(),
        Err(status) => status.into_response(),
    }
}

async fn login(Json(req): Json<LoginRequest>) -> impl IntoResponse {
    let pool = match db_pool().await {
        Ok(pool) => pool,
        Err(status) => return status.into_response(),
    };

    let row = match sqlx::query("SELECT id, password_hash FROM users WHERE email = $1")
        .bind(&req.email)
        .fetch_optional(&pool)
        .await
    {
        Ok(row) => row,
        Err(_) => return StatusCode::INTERNAL_SERVER_ERROR.into_response(),
    };

    let row = match row {
        Some(row) => row,
        None => return StatusCode::UNAUTHORIZED.into_response(),
    };

    let user_id: Uuid = row.get("id");
    let password_hash: String = row.get("password_hash");

    let parsed_hash = match PasswordHash::new(&password_hash) {
        Ok(hash) => hash,
        Err(_) => return StatusCode::INTERNAL_SERVER_ERROR.into_response(),
    };

    if Argon2::default()
        .verify_password(req.password.as_bytes(), &parsed_hash)
        .is_err()
    {
        return StatusCode::UNAUTHORIZED.into_response();
    }

    match issue_tokens(user_id).await {
        Ok(response) => (StatusCode::OK, Json(response)).into_response(),
        Err(status) => status.into_response(),
    }
}

async fn refresh(Json(req): Json<RefreshRequest>) -> impl IntoResponse {
    let claims = match decode::<Claims>(
        &req.refresh_token,
        &DecodingKey::from_secret(jwt_secret().as_bytes()),
        &Validation::default(),
    ) {
        Ok(data) => data.claims,
        Err(_) => return StatusCode::UNAUTHORIZED.into_response(),
    };

    if claims.token_type != "refresh" {
        return StatusCode::UNAUTHORIZED.into_response();
    }

    let user_id = match claims.sub.parse::<Uuid>() {
        Ok(id) => id,
        Err(_) => return StatusCode::UNAUTHORIZED.into_response(),
    };

    let mut hasher = Sha256::new();
    hasher.update(req.refresh_token.as_bytes());
    let token_hash = format!("{:x}", hasher.finalize());

    let pool = match db_pool().await {
        Ok(pool) => pool,
        Err(status) => return status.into_response(),
    };

    let row = match sqlx::query(
        "SELECT id, expires_at, revoked FROM refresh_tokens WHERE token_hash = $1",
    )
    .bind(&token_hash)
    .fetch_optional(&pool)
    .await
    {
        Ok(row) => row,
        Err(_) => return StatusCode::INTERNAL_SERVER_ERROR.into_response(),
    };

    let row = match row {
        Some(row) => row,
        None => return StatusCode::UNAUTHORIZED.into_response(),
    };

    let revoked: bool = row.get("revoked");
    let expires_at: chrono::DateTime<Utc> = row.get("expires_at");
    if revoked || expires_at < Utc::now() {
        return StatusCode::UNAUTHORIZED.into_response();
    }

    let token_id: Uuid = row.get("id");
    let _ = sqlx::query("UPDATE refresh_tokens SET revoked = true WHERE id = $1")
        .bind(token_id)
        .execute(&pool)
        .await;

    match issue_tokens(user_id).await {
        Ok(response) => (StatusCode::OK, Json(response)).into_response(),
        Err(status) => status.into_response(),
    }
}

async fn logout(Json(req): Json<RefreshRequest>) -> impl IntoResponse {
    let mut hasher = Sha256::new();
    hasher.update(req.refresh_token.as_bytes());
    let token_hash = format!("{:x}", hasher.finalize());

    let pool = match db_pool().await {
        Ok(pool) => pool,
        Err(status) => return status.into_response(),
    };

    let _ = sqlx::query("UPDATE refresh_tokens SET revoked = true WHERE token_hash = $1")
        .bind(token_hash)
        .execute(&pool)
        .await;

    StatusCode::NO_CONTENT.into_response()
}

